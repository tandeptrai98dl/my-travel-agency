import { z } from "zod";

import { IMAGE_EXTENSION, IMAGE_MIME, type ImageKind } from "./media.sniff";

export const MAX_UPLOAD_BYTES = 20 * 1024 * 1024; // matches the `media` bucket limit
/** Originals at least this long on the long edge (DESIGN_SYSTEM.md "Imagery"); smaller ones warn. */
export const RECOMMENDED_LONG_EDGE = 2400;
/** Refuse absurd dimensions and pixel counts before decoding (decompression bombs, memory). */
export const MAX_DIMENSION = 12_000;
export const MAX_PIXELS = 50_000_000;
/** AVIF decoding and encoding need far more memory per pixel (40 MP peaked at 1.7 GB). */
export const MAX_AVIF_PIXELS = 24_000_000;
export const MEDIA_PAGE_SIZE = 24;

const kinds = Object.keys(IMAGE_MIME) as ImageKind[];
const mimeToKind = Object.fromEntries(kinds.map((kind) => [IMAGE_MIME[kind], kind])) as Record<string, ImageKind>;

/** First step of an upload: what the browser says it will send (re-checked after upload). */
export const createUploadSchema = z.object({
  fileName: z.string().trim().min(1).max(255),
  size: z.number().int().positive().max(MAX_UPLOAD_BYTES),
  contentType: z.enum(kinds.map((kind) => IMAGE_MIME[kind]) as [string, ...string[]]),
});

const UUID = "[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}";
/** Staged uploads are generated by the server: pending/<user id>/<uuid>.<ext> in `media-uploads`. */
export const STAGED_PATH = new RegExp(`^pending/(${UUID})/(${UUID})\\.(jpg|png|webp|avif)$`);
/** Public copies: yyyy/mm/<uuid>.<ext> in `media`. */
export const MEDIA_PATH = new RegExp(`^\\d{4}/\\d{2}/${UUID}\\.(jpg|png|webp|avif)$`);

/** The name as uploaded, for search only: control characters dropped, length capped. */
export function cleanFileName(name: string): string {
  return name.replace(/[\u0000-\u001f\u007f]/g, "").trim().slice(0, 255);
}

export const finalizeUploadSchema = z.object({
  path: z.string().regex(STAGED_PATH),
  fileName: z.string().max(1000).transform(cleanFileName),
});

const altText = z.string().trim().max(300);

export const updateMediaSchema = z.object({
  id: z.uuid(),
  alt: z.object({ vi: altText, en: altText }),
  credit: z.string().trim().max(200).nullable(),
});

export const mediaIdSchema = z.object({ id: z.uuid() });

export const listMediaSchema = z.object({
  q: z.string().trim().max(100).catch(""),
  page: z.coerce.number().int().min(1).max(10_000).catch(1),
});

export function kindForMime(mime: string): ImageKind | null {
  return mimeToKind[mime] ?? null;
}

export function extensionOf(path: string): string {
  return path.slice(path.lastIndexOf(".") + 1);
}

export function kindMatchesExtension(kind: ImageKind, path: string): boolean {
  return IMAGE_EXTENSION[kind] === extensionOf(path);
}

/** Characters with meaning in PostgREST filter strings are dropped from free-text search. */
export function sanitizeSearch(q: string): string {
  return q.replace(/[,()*%\\:"']/g, " ").replace(/\s+/g, " ").trim();
}

export type MediaAlt = { vi: string; en: string };

export type MediaItem = {
  id: string;
  path: string;
  /** File name as uploaded (null for images recorded before it was kept). */
  originalName: string | null;
  url: string;
  mimeType: string;
  width: number | null;
  height: number | null;
  sizeBytes: number;
  blurDataUrl: string | null;
  alt: MediaAlt;
  credit: string | null;
  createdAt: string;
  /** Long edge under the recommended size: show a warning, do not block. */
  small: boolean;
  /** Both alt texts present: required before use in published content (decision 6). */
  altComplete: boolean;
};

export function readAlt(value: unknown): MediaAlt {
  const alt = (value ?? {}) as Partial<Record<string, unknown>>;
  return {
    vi: typeof alt.vi === "string" ? alt.vi : "",
    en: typeof alt.en === "string" ? alt.en : "",
  };
}

export function isSmall(width: number | null, height: number | null): boolean {
  if (width == null || height == null) return false;
  return Math.max(width, height) < RECOMMENDED_LONG_EDGE;
}
