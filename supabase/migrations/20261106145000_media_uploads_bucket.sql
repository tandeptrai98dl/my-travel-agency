-- Media uploads land in a private staging bucket first (ADR-023, PR 9 review). The browser
-- sends the original to `media-uploads/pending/<user id>/<uuid>.<ext>` through a signed URL;
-- the server then checks the bytes, re-encodes the image with sharp (which drops EXIF/GPS data
-- and anything appended after the image) and writes the clean copy to the public `media` bucket
-- with the service role. Nothing a browser sends is ever served from the public bucket.
--
-- `media-uploads` has no policies for API roles: only the service role signs uploads into it,
-- reads and deletes from it. Abandoned uploads are removed by a daily cleanup (Phase 6).

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('media-uploads', 'media-uploads', false, 20971520,
        array['image/jpeg', 'image/png', 'image/webp', 'image/avif'])
on conflict (id) do nothing;

-- Staff no longer write to the public bucket directly; the server writes checked copies there
-- with the service role. Read (listing) and delete (removing an unused image) stay.
drop policy "media bucket: staff insert" on storage.objects;
drop policy "media bucket: staff update" on storage.objects;

-- The file name as the editor uploaded it, for search in the library (decision 6). Paths are
-- generated by the server, so they carry no meaning of their own.
alter table public.media
  add column original_name text check (char_length(original_name) <= 255);

-- A media row must describe a file the server checked (PR 9 review): staff may change only the
-- descriptive columns, and new rows must look like what finalizeUpload() writes.
revoke update on public.media from authenticated;
grant update (alt, credit) on public.media to authenticated;

alter table public.media
  add constraint media_bucket_is_media check (bucket = 'media'),
  add constraint media_path_format check (
    path ~ '^[0-9]{4}/[0-9]{2}/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.(jpg|png|webp|avif)$'
  ),
  add constraint media_mime_type_image check (mime_type in ('image/jpeg', 'image/png', 'image/webp', 'image/avif')),
  add constraint media_blur_data_url_webp check (blur_data_url ~ '^data:image/webp;base64,[A-Za-z0-9+/=]+$');
